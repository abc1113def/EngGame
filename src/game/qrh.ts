import type { L, SimState } from '../sim/types';

/**
 * Книга QRH (A320) и раздел аварийных процедур РЛЭ (Cessna 172S).
 * Тексты — собственные упрощённые формулировки по смыслу типовых процедур.
 * Только для игры: не использовать в реальной эксплуатации.
 */
export interface QrhLine {
  ch?: string; // действие (англ., как на табличках)
  resp?: string; // ответ / положение
  t?: L; // поясняющий текст, условие или заголовок блока
  kind?: 'cond' | 'note' | 'head' | 'warn';
  ind?: number; // отступ (подпункт)
}
export interface QrhProc {
  id: string;
  title: L;
  color: 'red' | 'amber' | 'blue' | 'gray';
  lines: QrhLine[];
  /** активна ли процедура сейчас (подсветка в оглавлении) */
  active?: (s: SimState) => boolean;
}
export interface QrhChapter {
  id: string;
  title: L;
  procs: QrhProc[];
}

const r = (ru: string, en: string): L => ({ ru, en });
const A = (ch: string, resp: string, ind?: number): QrhLine => ({ ch, resp, ind });
const IF = (ru: string, en: string, ind = 0): QrhLine => ({ t: r(ru, en), kind: 'cond', ind });
const NOTE = (ru: string, en: string): QrhLine => ({ t: r(ru, en), kind: 'note' });
const H = (ru: string, en: string): QrhLine => ({ t: r(ru, en), kind: 'head' });
const WARN = (ru: string, en: string): QrhLine => ({ t: r(ru, en), kind: 'warn' });
const ecam = (s: SimState, ...ids: string[]) => s.type === 'a320' && s.ecam.active.some((a) => ids.includes(a.id));

